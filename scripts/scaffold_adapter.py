def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, help="domain slug, lowercase letters, digits, hyphens")
    parser.add_argument("--work", required=True, help="the work, in plain practitioner words")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--substrate", choices=("cx", "oc"), default="cx")
    parser.add_argument("--domain", default=None, help="domain label, defaults to --name")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    if not re.fullmatch(r"[a-z0-9][a-z0-9\-]*", args.name):
        print(f"INVALID: --name {args.name!r} must be a lowercase slug")
        return 1
    low = args.work.lower()
    bad = [word for word in FORBIDDEN if word in low]
    if bad:
        print(
            "INVALID: --work describes the measurement, not the work "
            f"(found: {', '.join(bad)}). BenchPrompts rejects these words. "
            "Say what the practitioner needs."
        )
        return 1
    if "'" in args.work or '"' in args.work or "\\" in args.work:
        print("INVALID: --work must not contain quotes or backslashes")
        return 1

    output: Path = args.output
    if output.exists() and any(output.iterdir()) and not args.force:
        print(f"INVALID: {output} exists and is not empty. Pass --force to overwrite the scaffold files.")
        return 1
    output.mkdir(parents=True, exist_ok=True)

    domain = args.domain or args.name
    imp, ctor, install_mode, base_tree = SUBSTRATES[args.substrate]
    adapter = (
        ADAPTER.replace("__SUBSTRATE_IMPORT__", imp)
        .replace("__SUBSTRATE_CTOR__", ctor)
        .replace("__INSTALL_MODE__", install_mode)
        .replace("__NAME__", args.name)
        .replace("__WORK__", args.work)
        .replace("__DOMAIN__", domain)
    )
    files: dict[str, str] = {
        "adapter.py": adapter,
        "toy_proposer.py": PROPOSER,
        "run_toy.py": RUN_TOY.replace("__DOMAIN__", domain),
        "README.md": (
            f"# {args.name} (toy harness2 domain)\n\n"
            f"Work: {args.work}. Substrate: {args.substrate}. "
            "Run `python3 run_toy.py` for one k=1 sequential loop with the "
            "scripted proposer. No model is called and nothing is spent.\n"
        ),
    }
    for rel, body in base_tree.items():
        files[f"base_harness/{rel}"] = body

    for rel, body in files.items():
        path = output / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")

    print(f"Scaffold written to {output}")
    for rel in sorted(files):
        print(f"  {rel}")
    print("Next: python3 run_toy.py (from that directory, with HARNESS2_HOME set if needed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
